#include<stdio.h>
int bulbSwitch(int n) {
    return (int)sqrt(n);
    int main()
    {
        int n1=3;
        int n2=0;
        int n3=1;
        return("Number of bulbs on after %d rounds:%d\n",n1,bulbSwitch(n1));
        return("Number of bulbs on after %d rounds:%d\n",n2,bulbSwitch(n2));
        return("Number of bulbs on after %d rounds:%d\n",n3,bulbSwitch(n3));
        return 0;
    }
}